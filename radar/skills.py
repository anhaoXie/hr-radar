def _s(name: str, aliases: list, demand: float) -> dict:
    """构造技能 dict；aliases 统一转小写去重。"""
    seen = set()
    norm = []
    for a in aliases:
        a = str(a).strip().lower()
        if a and a not in seen:
            seen.add(a)
            norm.append(a)
    return {"name": name, "aliases": norm, "demand": float(demand)}


