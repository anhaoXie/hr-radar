_AMBIGUOUS_RE: dict = {
    k: [re.compile(p) for p in v] for k, v in _AMBIGUOUS_ALIASES.items()
}


_ALIAS_PATTERNS: list = []
for _sk in ALL_SKILLS:
    for _alias in _sk["aliases"]:
        _ALIAS_PATTERNS.append((_sk["name"], _alias, _compile_alias(_alias)))


def extract_skills(text: str) -> list:
    """从中文/英文混合文本中抽取规范技能名列表。

    大小写不敏感；英文按词边界匹配，中文别名按子串匹配；
    结果按技能在文本中首次出现的位置排序，去重。
    歧义别名（见 _AMBIGUOUS_ALIASES）需要上下文线索同时出现才计入。
    """
    if not text or not isinstance(text, str):
        return []
    lowered = text.lower()
    guard_cache: dict = {}
    best: dict = {}
    for name, alias, pattern in _ALIAS_PATTERNS:
        guards = _AMBIGUOUS_RE.get(alias.lower())
        if guards:
            ok = guard_cache.get(alias.lower())
            if ok is None:
                ok = any(g.search(lowered) for g in guards)
                guard_cache[alias.lower()] = ok
            if not ok:
                continue
        if pattern is None:
            pos = lowered.find(alias)
            if pos < 0:
                continue
        else:
            if alias not in lowered:
                continue
            m = pattern.search(lowered)
            if m is None:
                continue
            pos = m.start()
        cur = best.get(name)
        if cur is None or pos < cur:
            best[name] = pos
    return [n for n, _ in sorted(best.items(),
                                 key=lambda kv: (kv[1], _ORDER_INDEX.get(kv[0], 9999)))]


def canonical(name: str):
    """别名/展示名 -> 规范 name；找不到返回 None。"""
    if not name or not isinstance(name, str):
        return None
    key = name.strip().lower()
    if key in ALIAS_INDEX:
        return ALIAS_INDEX[key]
    if name in _NAME_TO_SKILL:
        return name
    return None


def skill_category(name: str) -> str:
    """返回技能所属分类，找不到返回 '其他'。"""
    canon = canonical(name)
    if canon is None:
        return "其他"
    sk = _NAME_TO_SKILL.get(canon)
    return sk["category"] if sk else "其他"


def skill_demand(name: str) -> float:
    """返回技能市场热度权重（0.5~1.5），找不到返回 1.0。"""
    canon = canonical(name)
    if canon is None:
        return 1.0
    sk = _NAME_TO_SKILL.get(canon)
    return float(sk["demand"]) if sk else 1.0


